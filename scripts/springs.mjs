import { pathToFileURL } from 'node:url';

// Spring curves for app.css, as CSS linear() easings. Run it and paste the output over the
// block between the "springs" markers in app.css; test/springs.test.mjs checks they agree.
//
// The model is a damped spring described by a perceptual duration and a bounce, as in
// Liquid Glass (github.com/Glass-HQ/liquid-glass) and SwiftUI: stiffness (2π / duration)²,
// damping ratio 1 − bounce. A CSS transition has to last until the spring has settled, which
// is longer than the perceptual duration, so each curve comes with its own length.

// Pressing is quick and firm, letting go overshoots like a gel and settles; layout and
// morph move whole surfaces, so they bounce less. The switch uses the measured iOS spring
// (response 0.47 s, damping 0.7).
export const SPRINGS = {
  press: { duration: 0.24, bounce: 0.2 },
  release: { duration: 0.5, bounce: 0.42 },
  layout: { duration: 0.4, bounce: 0.16 },
  morph: { duration: 0.42, bounce: 0.18 },
  switch: { duration: 0.47, bounce: 0.3 },
};

// Progress from 0 to 1 at time t (seconds), for a spring starting at rest.
export function springAt({ duration, bounce }, t) {
  const omega = (2 * Math.PI) / duration;
  const zeta = 1 - bounce;
  const wd = omega * Math.sqrt(1 - zeta * zeta);
  return 1 - Math.exp(-zeta * omega * t) * (Math.cos(wd * t) + ((zeta * omega) / wd) * Math.sin(wd * t));
}

// Seconds until the spring stays within `precision` of its target.
export function settleTime(spring, precision = 0.002) {
  const step = 1 / 240;
  let last = 0;
  for (let t = 0; t < 3; t += step) if (Math.abs(springAt(spring, t) - 1) > precision) last = t;
  return Math.ceil((last + step) * 100) / 100;
}

export function linearEasing(spring, points = 48) {
  const length = settleTime(spring);
  const values = [];
  for (let i = 0; i <= points; i++) values.push(i === points ? 1 : springAt(spring, (length * i) / points));
  return { length, easing: `linear(${values.map((v) => +v.toFixed(3)).join(', ')})` };
}

export function springCSS() {
  const lines = ['/* springs: generated by scripts/springs.mjs */', '@supports (transition-timing-function: linear(0, 1)) {', '  :root {'];
  for (const [name, spring] of Object.entries(SPRINGS)) {
    const { length, easing } = linearEasing(spring);
    lines.push(`    --spring-${name}: ${easing};`, `    --spring-${name}-t: ${length}s;`);
  }
  lines.push('  }', '}', '/* end springs */');
  return lines.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) console.log(springCSS());
