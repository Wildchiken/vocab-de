export const MESSAGES = { zh, en };
export const LANGS = ['zh', 'en'];

let lang = 'zh';

export function detectLang(pref) {
  if (LANGS.includes(pref)) return pref;
  const sys = (navigator.languages?.[0] || navigator.language || 'en').toLowerCase();
  return sys.startsWith('zh') ? 'zh' : 'en';
}

export function setLang(l) {
  lang = LANGS.includes(l) ? l : 'en';
}

export const getLang = () => lang;
export const locale = () => (lang === 'zh' ? 'zh-CN' : 'en');

export function t(key, params = {}) {
  const v = MESSAGES[lang][key] ?? MESSAGES.zh[key] ?? key;
  if (typeof v === 'function') return v(params);
  return v.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '');
}

export function fmtIvl(ms) {
  const m = ms / 60_000;
  if (m < 60) return t('ivl.m', { n: Math.max(1, Math.round(m)) });
  const h = m / 60;
  if (h < 20) return t('ivl.h', { n: Math.round(h) });
  const d = ms / 86_400_000;
  if (d < 30) return t('ivl.d', { n: Math.round(d) });
  if (d < 365) return t('ivl.mo', { n: +(d / 30).toFixed(1) });
  return t('ivl.y', { n: +(d / 365).toFixed(1) });
}
